"""Extracts the lowercase "t" of Newsreader as an SVG path for the stocktruffle logo mark.

Run from the repository root:
    uv run --with fonttools --with brotli python scripts/build-logo.py

Writes apps/web/src/components/brand/logo-paths.ts. The path is in font units with the
y axis already flipped for SVG; the logo component scales and places it.
"""

import re
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

FONT = Path(
    "apps/web/node_modules/@fontsource-variable/newsreader/files/"
    "newsreader-latin-opsz-normal.woff2"
)
OUT = Path("apps/web/src/components/brand/logo-paths.ts")
# A display cut with some weight, so the letter holds up at favicon size.
LOCATION = {"opsz": 72, "wght": 560}


def rounded(commands: str) -> str:
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".removesuffix(".0"), commands)


def main() -> None:
    font = TTFont(FONT)
    axes = {axis.axisTag: axis for axis in font["fvar"].axes}
    location = {
        tag: max(axes[tag].minValue, min(axes[tag].maxValue, value))
        for tag, value in LOCATION.items()
        if tag in axes
    }
    static = instancer.instantiateVariableFont(font, location)
    glyphs = static.getGlyphSet()
    glyph_name = static.getBestCmap()[ord("t")]

    bounds = BoundsPen(glyphs)
    glyphs[glyph_name].draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds

    # Flip y and move the glyph's bounding box to the origin.
    svg = SVGPathPen(glyphs)
    glyphs[glyph_name].draw(TransformPen(svg, (1, 0, 0, -1, -x_min, y_max)))

    width, height = x_max - x_min, y_max - y_min
    OUT.write_text(
        "// Generated by scripts/build-logo.py from Newsreader "
        f"(opsz {location.get('opsz')}, wght {location.get('wght')}). Do not edit.\n"
        f'export const LETTER_T = "{rounded(svg.getCommands())}"\n'
        f"export const LETTER_T_WIDTH = {width:g}\n"
        f"export const LETTER_T_HEIGHT = {height:g}\n",
        encoding="utf-8",
    )
    print(f"{OUT}: {glyph_name}, {width:g} x {height:g} units at {location}")


if __name__ == "__main__":
    main()
